function getPath(obj, path) {
  return path.split(".").reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);
}

/**
 * Translate a namespaced key for a language, with {var} interpolation.
 * Falls back to English, then to the key itself, so the UI never shows blanks.
 */
export function translate(lang, key, vars) {
  let value = getPath(translations[lang], key);
  if (value == null) value = getPath(translations[DEFAULT_LANGUAGE], key);
  if (value == null) return key;
  if (vars) {
    value = value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] != null ? vars[name] : `{${name}}`));
  }
  return value;
}
